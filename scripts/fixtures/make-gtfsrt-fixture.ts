/**
 * Generates the synthetic Miami GTFS-realtime fixtures under `src/domain/gtfsrt/__fixtures__/`:
 *   - `vehicle-positions.fixture.ts` — four in-scope vehicles, for the decoder tests and the
 *     on-device decode probe (M1.13 / M1.16);
 *   - `live-feeds.fixture.ts` — the realtime mapper's cases (M4.2): the same four vehicles plus
 *     vehicles with no trip_id (one per branch, one on each shared trunk), a trip the schedule does
 *     not know, out-of-scope routes and a vehicle with no position; and a Swiftly-style TripUpdates
 *     feed (predictions, a canceled trip, a delay-only stop, a skipped stop, unusable updates).
 * Each feed is ENCODED by the reference GTFS-realtime bindings (the test oracle; Mac-side only, never
 * shipped), DECODED by our own decoder, and written as the bytes plus that decoded value;
 * oracle.test.ts then proves the reference decoder reads the same bytes identically.
 *
 * Deterministic by construction: fixed timestamps, no clock, no time zone, no randomness — so a
 * rerun reproduces both files byte for byte. Run from the repo root:
 *   npx tsx scripts/fixtures/make-gtfsrt-fixture.ts
 */

