type StopUpdateSpec = {
  readonly stopId: string | null;
  readonly sequence: number;
  /** Seconds after the feed timestamp the train departs (an absolute departure.time), or absent. */
  readonly inS?: number;
  readonly delay?: number;
  readonly relationship?: number;
};

