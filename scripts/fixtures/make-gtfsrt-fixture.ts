function vehicleEntity(spec: VehicleSpec): transit_realtime.IFeedEntity {
  invariant(spec.secondsOld === null || (spec.secondsOld >= 0 && spec.secondsOld < 300), 'fixture vehicles are a few seconds to minutes old');
  invariant(spec.at === null || (spec.at[0] > 25 && spec.at[0] < 26.5 && spec.at[1] > -81 && spec.at[1] < -80), 'fixture vehicles are in Miami');
  const stop = spec.stop === undefined ? {} : { stopId: spec.stop.stopId, currentStatus: spec.stop.status, currentStopSequence: spec.stop.sequence };
  const trip = spec.tripId === null ? {} : { tripId: spec.tripId };
  const position = spec.at === null ? {} : { position: { latitude: spec.at[0], longitude: spec.at[1], bearing: spec.bearing, speed: spec.speed } };
  const timestamp = spec.secondsOld === null ? {} : { timestamp: FEED_TIMESTAMP - spec.secondsOld };
  return {
    id: `vehicle-${spec.id}`,
    vehicle: {
      trip: { ...trip, routeId: spec.routeId, directionId: spec.directionId, startDate: '20261001' },
      vehicle: { id: spec.id, label: spec.label },
      ...position,
      ...timestamp,
      ...stop,
    },
  };
}

function stopTimeUpdateOf(spec: StopUpdateSpec): transit_realtime.TripUpdate.IStopTimeUpdate {
  invariant(spec.sequence >= 0, 'a stop update has a stop sequence');
  invariant(spec.inS === undefined || spec.inS > 0, 'a predicted departure lies after the feed timestamp');
  const time = spec.inS === undefined ? {} : { time: FEED_TIMESTAMP + spec.inS };
  const delay = spec.delay === undefined ? {} : { delay: spec.delay };
  return {
    stopSequence: spec.sequence,
    ...(spec.stopId === null ? {} : { stopId: spec.stopId }),
    ...(spec.inS === undefined && spec.delay === undefined ? {} : { departure: { ...time, ...delay } }),
    ...(spec.relationship === undefined ? {} : { scheduleRelationship: spec.relationship }),
  };
}

function tripUpdateEntity(spec: TripUpdateSpec): transit_realtime.IFeedEntity {
  invariant(spec.relationship === TRIP_CANCELED || spec.stops.length > 0, 'only a canceled trip lists no stops');
  invariant(spec.stops.every((s, i) => i === 0 || s.sequence > (spec.stops[i - 1]?.sequence ?? 0)), 'stop updates come in stop order');
  const stopTimeUpdate = spec.stops.map((stop) => stopTimeUpdateOf(stop));
  return {
    id: spec.id,
    tripUpdate: {
      trip: { tripId: spec.tripId, routeId: spec.routeId, directionId: spec.directionId, startDate: '20261001', scheduleRelationship: spec.relationship },
      stopTimeUpdate,
      timestamp: FEED_TIMESTAMP,
    },
  };
}

/** The feed encoded by the reference bindings, as a plain Uint8Array (not a Node Buffer). */
function encodeFeed(entity: transit_realtime.IFeedEntity[]): Uint8Array {
  invariant(entity.length > 0, 'a fixture feed has entities');
  const plain: transit_realtime.IFeedMessage = {
    header: { gtfsRealtimeVersion: '2.0', incrementality: 0, timestamp: FEED_TIMESTAMP },
    entity,
  };
  const problem = transit_realtime.FeedMessage.verify(plain);
  invariant(problem === null, `the fixture feed is a valid FeedMessage: ${String(problem)}`);
  const bytes = Uint8Array.from(transit_realtime.FeedMessage.encode(transit_realtime.FeedMessage.fromObject(plain)).finish());
  invariant(bytes.length > 0, 'the encoded feed has bytes');
  return bytes;
}

function formatBytes(bytes: Uint8Array): string {
  invariant(bytes.length > 0, 'there are bytes to format');
  const lines: string[] = [];
  for (let at = 0; at < bytes.length; at += BYTES_PER_LINE) {
    const row = Array.from(bytes.subarray(at, at + BYTES_PER_LINE), (byte) => `0x${byte.toString(16).padStart(2, '0')},`);
    lines.push(`  ${row.join(' ')}`);
  }
  invariant(lines.length === Math.ceil(bytes.length / BYTES_PER_LINE), 'one line per 16 bytes');
  return lines.join('\n');
}

/** One generated feed: its export-name prefix and a one-line description (`{n}` = entities, `{bytes}` = size). */
type FeedOutput = { readonly name: string; readonly about: string; readonly entity: transit_realtime.IFeedEntity[] };

/** The bytes and decoded value of one feed, as two exports `<name>_BYTES` and `<name>_DECODED`. */
function renderFeed(feed: FeedOutput): string[] {
  const bytes = encodeFeed(feed.entity);
  const decoded = decodeFeedMessage(bytes);
  invariant(decoded.ok, `our decoder reads the ${feed.name} fixture: ${decoded.ok ? '' : decoded.error.message}`);
  invariant(decoded.value.entity.length === feed.entity.length, `every ${feed.name} entity decoded`);
  const about = feed.about.replace('{n}', String(feed.entity.length)).replace('{bytes}', String(bytes.length));
  return [
    `/** ${about} */`,
    `export const ${feed.name}_BYTES: Uint8Array = new Uint8Array([`,
    formatBytes(bytes),
    ']);',
    '',
    `/** What \`decodeFeedMessage(${feed.name}_BYTES)\` returns (oracle.test.ts proves the reference decoder agrees). */`,
    `export const ${feed.name}_DECODED: FeedMessage = ${JSON.stringify(decoded.value, null, 2)};`,
    '',
  ];
}

function renderFixture(feeds: readonly FeedOutput[]): string {
  invariant(feeds.length > 0, 'a fixture file holds at least one feed');
  const blocks = feeds.flatMap((feed) => renderFeed(feed));
  const text = [GENERATED_BANNER, "import type { FeedMessage } from '../types';", '', ...blocks].join('\n');
  invariant(!text.includes('\r'), 'the fixture uses LF line endings on every platform');
  return text;
}

function writeFixture(file: string, feeds: readonly FeedOutput[]): void {
  invariant(file.endsWith('.fixture.ts'), 'fixtures are named *.fixture.ts');
  const path = `${FIXTURE_DIR}/${file}`;
  const text = renderFixture(feeds);
  mkdirSync(dirname(join(process.cwd(), path)), { recursive: true });
  writeFileSync(path, text, 'utf8');
  invariant(statSync(path).size === Buffer.byteLength(text, 'utf8'), `${path} was written in full`);
  console.log(`wrote ${path} (${feeds.map((feed) => `${feed.name}: ${feed.entity.length} entities`).join(', ')})`);
}

function main(): number {
  invariant(existsSync('package.json') && existsSync('src/domain/gtfsrt'), 'run the generator from the repo root');
  invariant(MAPPER_VEHICLES.slice(0, VEHICLES.length).every((spec, i) => spec === VEHICLES[i]), 'the mapper feed starts with the probe vehicles');
  writeFixture('vehicle-positions.fixture.ts', [
    { name: 'VEHICLE_POSITIONS_FIXTURE', about: 'A synthetic Miami GTFS-realtime VehiclePositions feed: {n} vehicles, {bytes} bytes.', entity: VEHICLES.map(vehicleEntity) },
  ]);
  writeFixture('live-feeds.fixture.ts', [
    { name: 'LIVE_VEHICLES_FIXTURE', about: 'The realtime mapper’s VehiclePositions feed (M4.2): {n} vehicles, {bytes} bytes.', entity: MAPPER_VEHICLES.map(vehicleEntity) },
    { name: 'LIVE_TRIP_UPDATES_FIXTURE', about: 'The realtime mapper’s Swiftly-style TripUpdates feed (M4.2): {n} trips, {bytes} bytes.', entity: TRIP_UPDATES.map(tripUpdateEntity) },
  ]);
  return 0;
}

process.exitCode = main();
